#!/usr/bin/env node
// Wallbreaker's Puzzle solver: plays every Puzzle wall headless with the real engine and finds a
// short sequence of shots that clears it (greedy search with a small beam over aim angles).
// The result goes into games/wallbreaker/src/puzzles.gen.js: per wall the par (shots the solver
// needed) and its solution. The game allows par + 2 shots; tests/wallbreaker.mjs replays every
// solution, so a wall that can't be cleared, or a change to the physics that breaks one, fails.
//
//   npm run wallbreaker:puzzles            solve all walls and rewrite puzzles.gen.js
//   npm run wallbreaker:puzzles -- 12      solve one wall (1-based) and print it
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { PUZZLES, puzzleLevel } from "../games/wallbreaker/src/walls.js";
import { playPuzzle, SLACK } from "../games/wallbreaker/src/puzzle-play.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const only = process.argv[2] ? Number(process.argv[2]) - 1 : null;
const ANGLES = [];
for (let a = -78; a <= 78; a += 1.5) ANGLES.push(a);
const BEAM = 3, MAX_SHOTS = 12;

function damageLeft(e) {
  let hp = 0;
  for (const b of e.bricks) if (b.alive && b.t !== "steel" && b.t !== "portal") hp += b.hp + 1;
  return hp;
}

function solve(i) {
  const lvl = puzzleLevel(i);
  let beam = [{ angles: [], left: Infinity }];
  for (let shot = 1; shot <= MAX_SHOTS; shot++) {
    const next = [];
    for (const node of beam) {
      for (const a of ANGLES) {
        const angles = [...node.angles, a];
        const e = playPuzzle(lvl, angles, 99);
        if (e.result && e.result.cleared) return { par: shot, solution: angles };
        next.push({ angles, left: damageLeft(e) });
      }
    }
    next.sort((x, y) => x.left - y.left || Math.abs(x.angles.at(-1)) - Math.abs(y.angles.at(-1)));
    // Keep the best few, but not three near-identical angles.
    beam = [];
    for (const n of next) {
      if (beam.some((b) => b.left === n.left && Math.abs(b.angles.at(-1) - n.angles.at(-1)) < 6)) continue;
      beam.push(n);
      if (beam.length >= BEAM) break;
    }
  }
  return null;
}

const out = {};
let bad = 0;
for (let i = 0; i < PUZZLES.length; i++) {
  if (only != null && i !== only) continue;
  const t0 = Date.now();
  const r = solve(i);
  const name = PUZZLES[i].name;
  if (!r) { bad++; console.log(`✗ ${i + 1} ${name}: no solution within ${MAX_SHOTS} shots`); continue; }
  out[name] = r;
  console.log(`✓ ${String(i + 1).padStart(2)} ${name.padEnd(14)} par ${r.par}, limit ${r.par + SLACK}  (${((Date.now() - t0) / 1000).toFixed(1)} s)  ${r.solution.join(", ")}`);
}
if (only == null && !bad) {
  const body = `// Generated by scripts/wallbreaker-puzzles.mjs (npm run wallbreaker:puzzles). Do not edit by hand.\n` +
    `// Per Puzzle wall: par = the shots the solver needed; solution = its aim angles in degrees from straight up.\n` +
    `export const SOLUTIONS = ${JSON.stringify(out, null, 0).replace(/\},"/g, '},\n  "').replace(/^\{/, "{\n  ").replace(/\}\}$/, "}\n}")};\n`;
  writeFileSync(join(ROOT, "games/wallbreaker/src/puzzles.gen.js"), body);
  console.log("\nwrote games/wallbreaker/src/puzzles.gen.js");
}
process.exit(bad ? 1 : 0);
