#!/usr/bin/env node
// Works out Bubbleworks' first levels with the autoplayer and writes games/bubbleworks/src/levels.gen.js:
// for each level the salt that made a good board and the shots the autoplayer needed (the budget
// follows from that). Run it after changing src/levels.js, src/grid.js, src/bot.js or the rules;
// tests/bubbleworks/rules.test.mjs fails when a stored level no longer matches.
//
//   npm run bubbleworks:levels [-- 300]
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { solveLevel } from "../games/bubbleworks/src/levels.js";

const COUNT = Number(process.argv[2]) || 300;
const out = [];
const t0 = Date.now();
for (let n = 1; n <= COUNT; n++) {
  const l = solveLevel(n);
  out.push(`[${l.salt},${l.botShots}]`);
  if (n % 25 === 0) console.log(`level ${n} (${((Date.now() - t0) / 1000).toFixed(1)} s)`);
}
const file = join(dirname(fileURLToPath(import.meta.url)), "../games/bubbleworks/src/levels.gen.js");
const rows = [];
for (let i = 0; i < out.length; i += 10) rows.push("  " + out.slice(i, i + 10).join(", ") + ",");
writeFileSync(file, `// Generated by npm run bubbleworks:levels: do not edit by hand.
// Per level (from level 1): [salt, shots the autoplayer needed]. See src/levels.js.
export const SOLVED = [
${rows.join("\n")}
];
`);
console.log(`wrote ${COUNT} levels to ${file}`);
