#!/usr/bin/env node
// Downloads each game's Google Fonts into games/<slug>/fonts/ so the games work offline
// (an app on a phone in airplane mode must never depend on a CDN).
//
// Source of truth per game: games/<slug>/fonts/google-fonts.txt — one Google Fonts CSS URL per line.
// Output: games/<slug>/fonts/fonts.css + the .woff2 files it references.
//
// Only the "latin" and "latin-ext" slices are kept (that covers English, Dutch and other
// European languages). URLs that use Google's `text=` parameter are already an exact subset,
// so every face from those is kept.
//
// Usage:  node scripts/vendor-fonts.mjs            (all games)
//         node scripts/vendor-fonts.mjs outbound   (one game)
import { readdir, readFile, writeFile, rm, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
// A modern browser UA makes Google serve woff2 with unicode-range slices.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36";
const KEEP = new Set(["latin", "latin-ext"]);

const only = process.argv[2];
const games = (await readdir(join(ROOT, "games"), { withFileTypes: true }))
  .filter((d) => d.isDirectory() && (!only || d.name === only))
  .map((d) => d.name);

for (const slug of games) {
  const dir = join(ROOT, "games", slug, "fonts");
  const src = join(dir, "google-fonts.txt");
  if (!existsSync(src)) continue;
  const urls = (await readFile(src, "utf8")).split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));

  // Start clean so removed fonts do not linger.
  for (const f of await readdir(dir)) if (f.endsWith(".woff2") || f === "fonts.css") await rm(join(dir, f));
  await mkdir(dir, { recursive: true });

  const out = [`/* Generated by scripts/vendor-fonts.mjs from google-fonts.txt — do not edit by hand. */`];
  const downloaded = new Map();
  let bytes = 0;

  // Pass 1: collect the faces we want to keep.
  const faces = [];
  for (const url of urls) {
    const exactSubset = url.includes("text=");
    const css = await (await fetch(url, { headers: { "User-Agent": UA } })).text();
    // Google's CSS is a list of: optional "/* subset */" comment followed by an @font-face block.
    for (const m of css.matchAll(/(?:\/\*\s*([^*]+?)\s*\*\/\s*)?@font-face\s*{([^}]*)}/g)) {
      const subset = m[1] || "";
      if (!exactSubset && !KEEP.has(subset)) continue;
      const block = m[2];
      faces.push({
        block,
        subset: exactSubset ? "subset" : subset,
        family: /font-family:\s*'([^']+)'/.exec(block)[1],
        weight: (/font-weight:\s*([^;]+);/.exec(block) || [, "400"])[1].trim().replace(/\s+/g, "-"),
        italic: /font-style:\s*italic/.test(block),
        remote: /url\((https:[^)]+)\)/.exec(block)[1],
      });
    }
  }

  // Pass 2: name files. Variable fonts reuse one file for every weight, so the weight
  // only goes into the file name when a family really has separate files per weight.
  const filesPer = new Map();
  for (const f of faces) {
    const k = f.family + "|" + f.subset + "|" + f.italic;
    filesPer.set(k, (filesPer.get(k) || new Set()).add(f.remote));
  }
  for (const f of faces) {
    let file = downloaded.get(f.remote);
    if (!file) {
      const multi = filesPer.get(f.family + "|" + f.subset + "|" + f.italic).size > 1;
      file = [f.family.toLowerCase().replace(/\s+/g, "-"), multi && f.weight, f.italic && "italic", f.subset].filter(Boolean).join("-") + ".woff2";
      const buf = Buffer.from(await (await fetch(f.remote)).arrayBuffer());
      await writeFile(join(dir, file), buf);
      bytes += buf.length;
      downloaded.set(f.remote, file);
    }
    out.push(`/* ${f.subset} */\n@font-face {${f.block.replace(f.remote, file)}}`);
  }
  await writeFile(join(dir, "fonts.css"), out.join("\n") + "\n");
  console.log(`${slug}: ${downloaded.size} font files, ${(bytes / 1024).toFixed(0)} KB`);
}
